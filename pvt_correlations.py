# ---------------------------------------------------------------------------
# 1. Объёмный коэффициент воды Bw(P) — корреляция McCain
# ---------------------------------------------------------------------------
def bw_mccain(p_psi: float, t_f: float) -> float:
    """
    Объёмный коэффициент пластовой воды Bw(P) — корреляция McCain (1990),
    через изменение объёма воды за счёт температуры (dVwt) и давления (dVwp).
    Влияние солёности на сам Bw в этой упрощённой корреляции малó и им
    пренебрегают (McCain), в отличие от Bw без учёта растворённого газа.

    Диапазон применимости (field units):
        P: до 5000 psi
        T: 100 - 260 F
    Диапазон в метрике: P до ~345 бар, T ~38-127 °C

    Параметры
    ---------
    p_psi : давление, psia
    t_f   : температура, °F

    Возвращает
    ----------
    bw_bbl_stb : объёмный коэффициент воды, bbl/stb
    """
    dvwt = (
        -1.0001e-2 + 1.33391e-4 * t_f + 5.50654e-7 * t_f ** 2
    )
    dvwp = (
        -1.95301e-9 * p_psi * t_f - 1.72834e-13 * p_psi ** 2 * t_f
        - 3.58922e-7 * p_psi - 2.25341e-10 * p_psi ** 2
    )
    bw_bbl_stb = (1 + dvwt) * (1 + dvwp)
    return bw_bbl_stb


# ---------------------------------------------------------------------------
# 2. Вязкость воды μw(P) — с учётом солёности
# ---------------------------------------------------------------------------
def mu_water_mccain(p_psi: float, t_f: float, salinity_ppm: float = 0.0) -> float:
    """
    Вязкость пластовой воды μw(P,T) — корреляция McCain (1990) для
    μw при 14.7 psia, скорректированная на давление.

    Диапазон применимости (field units):
        T: 100 - 400 F
        Солёность: 0 - 300000 ppm (общая минерализация)
        P: до ~15000 psi (коррекция на давление слабая, но учитывается)
    Диапазон в метрике: T ~38-204 °C, солёность 0-300 г/л

    Параметры
    ---------
    p_psi        : давление, psia
    t_f          : температура, °F
    salinity_ppm : общая минерализация пластовой воды, ppm (мг/л)

    Возвращает
    ----------
    mu_w_cp : вязкость пластовой воды, сПз
    """
    s = salinity_ppm / 10000.0  # ppm -> % по массе (используется в корреляции)

    a = 109.574 - 8.40564 * s + 0.313314 * s ** 2 + 8.72213e-3 * s ** 3
    b = (
        -1.12166 + 2.63951e-2 * s - 6.79461e-4 * s ** 2
        - 5.47119e-5 * s ** 3 + 1.55586e-6 * s ** 4
    )
    mu_w1_cp = a * t_f ** b  # вязкость воды при 14.7 psia

    # коррекция на давление (небольшой рост вязкости с ростом P)
    p_factor = (
        0.9994 + 4.0295e-5 * p_psi + 3.1062e-9 * p_psi ** 2
    )
    mu_w_cp = mu_w1_cp * p_factor
    return mu_w_cp


# ---------------------------------------------------------------------------
# 3. Сжимаемость воды Cw — с учётом солёности и растворённого газа
# ---------------------------------------------------------------------------
def cw_water(p_psi: float, t_f: float, rsw_scf_stb: float = 0.0,
             salinity_ppm: float = 0.0) -> float:
    """
    Изотермическая сжимаемость пластовой воды Cw — корреляция McCain,
    рассчитанная для чистой воды и скорректированная на растворённый
    в воде газ (по умолчанию Rsw=0, т.к. растворимость газа в воде мала).

    Диапазон применимости (field units):
        P: 1000 - 20000 psi
        T: 200 - 270 F (базовая корреляция чистой воды Дорогокупца/Osif)
    Диапазон в метрике: P ~69-1379 бар, T ~93-132 °C

    Параметры
    ---------
    p_psi        : давление, psia
    t_f          : температура, °F
    rsw_scf_stb  : газосодержание в воде, scf/stb (обычно мало, по умолчанию 0)
    salinity_ppm : общая минерализация пластовой воды, ppm (для справки;
                   в упрощённом варианте Osif солёность снижает Cw незначительно
                   и здесь не используется в формуле явно)

    Возвращает
    ----------
    cw_per_psi : сжимаемость воды, 1/psi
    """
    # Корреляция Osif (1988) для чистой пластовой воды
    cw_per_psi = 1.0 / (
        7.033 * p_psi + 541.5 * salinity_ppm / 1000.0 - 537.0 * t_f + 403300.0
    )
    # небольшая поправка на растворённый газ (эмпирически, растёт с Rsw)
    cw_per_psi *= (1 + 0.0001 * rsw_scf_stb)
    return cw_per_psi
