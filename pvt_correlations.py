# ---------------------------------------------------------------------------
# 1. Псевдокритические свойства газа — корреляция Standing (sweet/wet gas)
# ---------------------------------------------------------------------------
def pseudo_critical_properties_standing(gamma_g: float) -> tuple[float, float]:
    """
    Псевдокритические давление и температура газа — корреляция Standing
    для "sweet" природного газа (без значимых примесей H2S/CO2).

    Диапазон применимости (field units):
        gamma_g: 0.57 - 1.68 (относительная плотность газа по воздуху)

    Параметры
    ---------
    gamma_g : относительная плотность газа по воздуху (безразмерная)

    Возвращает
    ----------
    (ppc_psi, tpc_r) : псевдокритическое давление (psia) и
                        псевдокритическая температура (Ranking, R)
    """
    ppc_psi = 677.0 + 15.0 * gamma_g - 37.5 * gamma_g ** 2
    tpc_r = 168.0 + 325.0 * gamma_g - 12.5 * gamma_g ** 2
    return ppc_psi, tpc_r


# ---------------------------------------------------------------------------
# 1б. Коррекция псевдокритических свойств на кислые компоненты (H2S, CO2) —
#     Wichert-Aziz (1972)
# ---------------------------------------------------------------------------
def wichert_aziz_correction(ppc_psi: float, tpc_r: float,
                             y_h2s: float, y_co2: float) -> tuple[float, float]:
    """
    Коррекция псевдокритических свойств газа на содержание кислых компонентов
    (H2S, CO2) — корреляция Wichert-Aziz (1972). Применяется ПОСЛЕ расчёта
    "обычных" (sweet gas) Ppc/Tpc — например, по pseudo_critical_properties_
    standing() — и ПЕРЕД расчётом приведённых давления/температуры для
    Z-фактора (DAK). Для месторождений без значимого H2S/CO2 (y_h2s=y_co2=0)
    поправка равна нулю и ничего не меняет.

    Актуально для казахстанских месторождений с сернистым/кислым газом
    (например, Тенгиз, Королёвское, Карачаганак — там H2S может достигать
    10-15+ мол.%, тогда как для "сладких" месторождений эта поправка обычно
    пренебрежимо мала, доли процента).

    Диапазон применимости (по исходной работе Wichert-Aziz):
        Сумма H2S+CO2 (мол. доля A): 0 - 0.85
        H2S (мол. доля B): 0 - 0.74
        Псевдоприведённое давление: до ~700 psia в исходных данных, но
        поправка широко используется и за этими пределами как стандарт
        отрасли (де-факто общепринятая корреляция)

    Параметры
    ---------
    ppc_psi : псевдокритическое давление ДО коррекции ("sweet"), psia
    tpc_r   : псевдокритическая температура ДО коррекции ("sweet"), R
    y_h2s   : мольная доля H2S в газе (0..1, НЕ проценты — 5% H2S -> 0.05)
    y_co2   : мольная доля CO2 в газе (0..1, НЕ проценты)

    Возвращает
    ----------
    (ppc_corrected_psi, tpc_corrected_r) : скорректированные псевдокритические
        давление и температура
    """
    if y_h2s <= 0 and y_co2 <= 0:
        return ppc_psi, tpc_r

    a = y_h2s + y_co2
    b = y_h2s

    # ε (эпсилон) — поправка на температуру, в градусах Ranking
    epsilon_r = 120.0 * (a ** 0.9 - a ** 1.6) + 15.0 * (b ** 0.5 - b ** 4.0)

    tpc_corrected_r = tpc_r - epsilon_r
    ppc_corrected_psi = (ppc_psi * tpc_corrected_r
                          / (tpc_r + b * (1.0 - b) * epsilon_r))

    return ppc_corrected_psi, tpc_corrected_r


def reduced_properties(p_psi: float, t_f: float, ppc_psi: float, tpc_r: float) -> tuple[float, float]:
    """
    Приведённые (псевдоприведённые) давление и температура газа.

    Параметры
    ---------
    p_psi   : давление, psia
    t_f     : температура, °F
    ppc_psi : псевдокритическое давление, psia
    tpc_r   : псевдокритическая температура, R

    Возвращает
    ----------
    (ppr, tpr) : псевдоприведённые давление и температура (безразмерные)
    """
    t_r = t_f + 459.67  # перевод в абсолютную шкалу Ranking
    ppr = p_psi / ppc_psi
    tpr = t_r / tpc_r
    return ppr, tpr


# ---------------------------------------------------------------------------
# 2. Z-фактор — корреляция Dranchuk-Abou-Kassem (DAK, 1975)
# ---------------------------------------------------------------------------
def z_factor_dak(ppr: float, tpr: float) -> float:
    """
    Коэффициент сверхсжимаемости газа Z по корреляции Dranchuk-Abou-Kassem
    (аппроксимация уравнения состояния Starling-Carnahan через диаграмму
    Standing-Katz). Решается итерационно (метод Ньютона).

    Диапазон применимости:
        Ppr: 0.2 - 30
        Tpr: 1.0 - 3.0

    Параметры
    ---------
    ppr : псевдоприведённое давление (безразмерное)
    tpr : псевдоприведённая температура (безразмерное)

    Возвращает
    ----------
    z : коэффициент сверхсжимаемости газа (безразмерный)
    """
    a1, a2, a3, a4, a5 = 0.3265, -1.0700, -0.5339, 0.01569, -0.05165
    a6, a7, a8, a9, a10, a11 = 0.5475, -0.7361, 0.1844, 0.1056, 0.6134, 0.7210

    def residual(z: float) -> float:
        rho_r = 0.27 * ppr / (z * tpr)
        c1 = a1 + a2 / tpr + a3 / tpr ** 3 + a4 / tpr ** 4 + a5 / tpr ** 5
        c2 = a6 + a7 / tpr + a8 / tpr ** 2
        c3 = a9 * (a7 / tpr + a8 / tpr ** 2)
        term = (
            1
            + c1 * rho_r
            + c2 * rho_r ** 2
            - c3 * rho_r ** 5
            + a10 * (1 + a11 * rho_r ** 2) * (rho_r ** 2 / tpr ** 3)
            * np.exp(-a11 * rho_r ** 2)
        )
        return z - term

    # Метод Ньютона с численной производной, старт с z=1
    z = 1.0
    for _ in range(50):
        f0 = residual(z)
        dz = 1e-6
        f1 = residual(z + dz)
        deriv = (f1 - f0) / dz
        if abs(deriv) < 1e-12:
            break
        z_new = z - f0 / deriv
        z_new = max(z_new, 0.05)  # физически Z не может быть отрицательным/нулевым
        if abs(z_new - z) < 1e-8:
            z = z_new
            break
        z = z_new

    return z


# ---------------------------------------------------------------------------
# 3. Объёмный коэффициент газа Bg(P)
# ---------------------------------------------------------------------------
def bg_gas(p_psi: float, t_f: float, z: float) -> float:
    """
    Объёмный коэффициент газа Bg(P) — из уравнения реального газа.

    Bg = (Psc / Tsc) * (Z*T / P)   [rcf/scf]
    при стандартных условиях Psc=14.696 psia, Tsc=519.67 R (60 F)

    Параметры
    ---------
    p_psi : давление, psia
    t_f   : температура, °F
    z     : коэффициент сверхсжимаемости газа (безразмерный)

    Возвращает
    ----------
    bg_rcf_scf : объёмный коэффициент газа, rcf/scf (res ft3 / scf)
    """
    t_r = t_f + 459.67
    psc_psi = 14.696
    tsc_r = 519.67
    bg_rcf_scf = (psc_psi / tsc_r) * (z * t_r / p_psi)
    return bg_rcf_scf


# ---------------------------------------------------------------------------
# 4. Вязкость газа — корреляция Lee-Gonzalez-Eakin (1966)
# ---------------------------------------------------------------------------
def mu_gas_lee_gonzalez_eakin(p_psi: float, t_f: float, z: float, gamma_g: float) -> float:
    """
    Вязкость природного газа по корреляции Lee-Gonzalez-Eakin (1966).

    Диапазон применимости (field units):
        P: 100 - 8000 psia
        T: 100 - 340 F
        CO2 до 3.2%, N2 до 4.8% (для чистых углеводородных газов точнее всего)
    Диапазон в метрике: P ~7-552 бар, T ~38-171 °C

    Параметры
    ---------
    p_psi   : давление, psia
    t_f     : температура, °F
    z       : коэффициент сверхсжимаемости газа
    gamma_g : относительная плотность газа по воздуху

    Возвращает
    ----------
    mu_g_cp : вязкость газа, сПз
    """
    t_r = t_f + 459.67
    m_air = 28.9647  # молярная масса воздуха, г/моль
    mw_g = gamma_g * m_air  # молярная масса газа, г/моль

    # молярная плотность газа, г/см3, через реальное уравнение состояния
    r = 10.732  # универсальная газовая постоянная, psia*ft3/(lb-mol*R)
    rho_g_g_cm3 = (p_psi * mw_g) / (z * r * t_r) * 0.0160185  # lb/ft3 -> г/см3

    k = ((9.4 + 0.02 * mw_g) * t_r ** 1.5) / (209.0 + 19.0 * mw_g + t_r)
    x = 3.5 + 986.0 / t_r + 0.01 * mw_g
    y = 2.4 - 0.2 * x

    mu_g_cp = 1e-4 * k * np.exp(x * rho_g_g_cm3 ** y)
    return mu_g_cp


