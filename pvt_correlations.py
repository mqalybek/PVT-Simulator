"""
pvt_correlations.py — классические PVT-корреляции Black Oil модели.

ВАЖНО: все функции в этом модуле принимают и возвращают величины ТОЛЬКО
в field units (американская система), т.к. исторически именно в них были
получены (регрессией по лабораторным данным) все классические корреляции:

    Давление        -> psi (абсолютное)
    Температура     -> °F
    Rs (газосодержание) -> scf/stb
    Bo              -> bbl/stb (rb/stb)
    Bg              -> rcf/scf
    Плотность нефти -> °API
    Вязкость        -> сПз (cP)
    Сжимаемость     -> 1/psi

Конвертация в метрическую систему (Казахстан) выполняется отдельно
в units.py и в UI (app.py). Формулы здесь НЕ трогаем.

ЭТАП 1: базовые корреляции нефти
    - Pb (давление насыщения)      — Standing (1947)
    - Rs(P)                        — Standing
    - Bo(P)                        — Standing
    - вязкость мёртвой нефти       — Beggs-Robinson
    - вязкость живой нефти <= Pb   — Beggs-Robinson (через Rs)
    - вязкость живой нефти > Pb    — Vasquez-Beggs (коррекция на сжимаемость)
    - Co выше Pb                   — Vasquez-Beggs
"""

from __future__ import annotations

import numpy as np

# ---------------------------------------------------------------------------
# 1. Давление насыщения Pb — корреляция Standing (1947)
# ---------------------------------------------------------------------------
def pb_standing(rsb_scf_stb: float, gamma_g: float, api: float, t_f: float) -> float:
    """
    Давление насыщения Pb по корреляции Standing (1947).

    Диапазон применимости (field units):
        API: 16.5 - 63.8
        Rsb: 20 - 1425 scf/stb
        T: 100 - 258 F
        Pb: 130 - 7000 psi
    Диапазон в метрике (для наглядности, Казахстан):
        плотность нефти: ~725 - 960 кг/м3
        Rsb: ~3.6 - 254 м3/м3
        T: ~38 - 126 °C
        Pb: ~9 - 483 бар

    Параметры
    ---------
    rsb_scf_stb : газосодержание при давлении насыщения (Rs при P=Pb), scf/stb
    gamma_g     : относительная плотность газа по воздуху (безразмерная)
    api         : плотность нефти, °API
    t_f         : пластовая температура, °F

    Возвращает
    ----------
    pb_psi : давление насыщения, psi (абсолютное)
    """
    if rsb_scf_stb <= 0:
        return 14.7  # атмосферное давление — газа в нефти нет

    cpb = (rsb_scf_stb / gamma_g) ** 0.83 * 10 ** (0.00091 * t_f - 0.0125 * api)
    pb_psi = 18.2 * (cpb - 1.4)
    return max(pb_psi, 14.7)


# ---------------------------------------------------------------------------
# 2. Газосодержание Rs(P) — корреляция Standing
# ---------------------------------------------------------------------------
def rs_standing(p_psi: float, pb_psi: float, rsb_scf_stb: float,
                 gamma_g: float, api: float, t_f: float) -> float:
    """
    Газосодержание Rs(P) по корреляции Standing.

    Ниже Pb — растёт с давлением (обращение формулы Pb относительно Rs).
    Выше Pb — постоянно и равно Rsb (в нефти растворён весь свободный газ).

    Диапазон применимости — см. pb_standing().

    Параметры
    ---------
    p_psi       : давление, при котором считаем Rs, psi
    pb_psi      : давление насыщения, psi
    rsb_scf_stb : газосодержание при давлении насыщения, scf/stb
    gamma_g     : относительная плотность газа по воздуху
    api         : плотность нефти, °API
    t_f         : температура, °F

    Возвращает
    ----------
    rs_scf_stb : газосодержание при давлении p_psi, scf/stb
    """
    if p_psi >= pb_psi:
        return rsb_scf_stb

    p_eff = max(p_psi, 14.7)
    x = 0.0125 * api - 0.00091 * t_f
    rs_scf_stb = gamma_g * ((p_eff / 18.2 + 1.4) * 10 ** x) ** 1.2048
    return max(rs_scf_stb, 0.0)


# ---------------------------------------------------------------------------
# 3. Объёмный коэффициент нефти Bo(P) — корреляция Standing
# ---------------------------------------------------------------------------
def bo_standing(p_psi: float, pb_psi: float, rs_scf_stb: float, rsb_scf_stb: float,
                 gamma_g: float, gamma_o: float, t_f: float,
                 co_per_psi: float | None = None) -> float:
    """
    Объёмный коэффициент нефти Bo(P) по корреляции Standing.

    Ниже и на Pb рассчитывается напрямую по корреляции Standing (Bob при
    насыщенной нефти, где Rs = Rs(P)).
    Выше Pb — Bo уменьшается относительно Bob за счёт сжимаемости
    недонасыщенной нефти (нужен Co, см. co_vasquez_beggs).

    Диапазон применимости (field units):
        API: 16.5 - 63.8
        Rs: 20 - 1425 scf/stb
        T: 100 - 258 F
        gamma_g: 0.59 - 1.40
    Диапазон в метрике: плотность ~725-960 кг/м3, Rs ~3.6-254 м3/м3,
        T ~38-126 °C

    Параметры
    ---------
    p_psi       : давление, psi
    pb_psi      : давление насыщения, psi
    rs_scf_stb  : газосодержание при данном давлении, scf/stb (= rsb при P>=Pb)
    rsb_scf_stb : газосодержание при давлении насыщения, scf/stb
    gamma_g     : относительная плотность газа
    gamma_o     : относительная плотность нефти (SG, вода=1)
    t_f         : температура, °F
    co_per_psi  : сжимаемость нефти выше Pb, 1/psi (обязательна, если p_psi > pb_psi)

    Возвращает
    ----------
    bo_bbl_stb : объёмный коэффициент нефти, bbl/stb (rb/stb)
    """
    f = rs_scf_stb * (gamma_g / gamma_o) ** 0.5 + 1.25 * t_f
    bob_bbl_stb = 0.9759 + 12.0e-5 * f ** 1.2

    if p_psi <= pb_psi:
        return bob_bbl_stb

    if co_per_psi is None:
        raise ValueError("Для P > Pb необходимо передать co_per_psi (сжимаемость нефти)")

    # Коррекция объёмного коэффициента насыщенной нефти на сжатие недонасыщенной нефти
    bo_bbl_stb = bob_bbl_stb * np.exp(co_per_psi * (pb_psi - p_psi))
    return bo_bbl_stb


# ---------------------------------------------------------------------------
# 4. Вязкость нефти
# ---------------------------------------------------------------------------
def mu_dead_oil_beggs_robinson(api: float, t_f: float) -> float:
    """
    Вязкость "мёртвой" нефти (без растворённого газа) — корреляция Beggs-Robinson (1975).

    Диапазон применимости (field units):
        API: 16 - 58
        T: 70 - 295 F
    Диапазон в метрике: плотность ~745-960 кг/м3, T ~21-146 °C

    Параметры
    ---------
    api : плотность нефти, °API
    t_f : температура, °F

    Возвращает
    ----------
    mu_od_cp : вязкость мёртвой нефти, сПз
    """
    z = 3.0324 - 0.02023 * api
    y = 10 ** z
    x = y * t_f ** (-1.163)
    mu_od_cp = 10 ** x - 1
    return mu_od_cp


def mu_live_oil_beggs_robinson(mu_dead_cp: float, rs_scf_stb: float) -> float:
    """
    Вязкость "живой" нефти (с растворённым газом) при P <= Pb —
    корреляция Beggs-Robinson (1975).

    Диапазон применимости (field units):
        Rs: 0 - 2070 scf/stb
        (тот же диапазон API, T, что и для мёртвой нефти)
    Диапазон в метрике: Rs ~0-368 м3/м3

    Параметры
    ---------
    mu_dead_cp : вязкость мёртвой нефти, сПз
    rs_scf_stb : газосодержание при данном давлении, scf/stb

    Возвращает
    ----------
    mu_o_cp : вязкость живой нефти при P <= Pb, сПз
    """
    a = 10.715 * (rs_scf_stb + 100) ** (-0.515)
    b = 5.44 * (rs_scf_stb + 150) ** (-0.338)
    mu_o_cp = a * mu_dead_cp ** b
    return mu_o_cp


def mu_oil_above_pb_vasquez_beggs(mu_ob_cp: float, p_psi: float, pb_psi: float) -> float:
    """
    Вязкость нефти выше давления насыщения (недонасыщенная нефть) —
    коррекция Vasquez-Beggs (1980).

    Диапазон применимости (field units):
        API: 15.3 - 59.5
        P: до 6055 psi
    Диапазон в метрике: плотность ~745-965 кг/м3, P до ~417 бар

    Параметры
    ---------
    mu_ob_cp : вязкость нефти при давлении насыщения (P=Pb), сПз
    p_psi    : давление, при котором считаем вязкость (P > Pb), psi
    pb_psi   : давление насыщения, psi

    Возвращает
    ----------
    mu_o_cp : вязкость нефти при P > Pb, сПз
    """
    m = 2.6 * p_psi ** 1.187 * np.exp(-11.513 - 8.98e-5 * p_psi)
    mu_o_cp = mu_ob_cp * (p_psi / pb_psi) ** m
    return mu_o_cp


def mu_oil(p_psi: float, pb_psi: float, rs_scf_stb: float, rsb_scf_stb: float,
           api: float, t_f: float) -> float:
    """
    Полный расчёт вязкости нефти μo(P) во всём диапазоне давлений:
    мёртвая нефть -> живая нефть (Beggs-Robinson) -> недонасыщенная нефть
    выше Pb (Vasquez-Beggs).

    Параметры
    ---------
    p_psi       : давление, psi
    pb_psi      : давление насыщения, psi
    rs_scf_stb  : газосодержание при данном давлении, scf/stb
    rsb_scf_stb : газосодержание при давлении насыщения, scf/stb
    api         : плотность нефти, °API
    t_f         : температура, °F

    Возвращает
    ----------
    mu_o_cp : вязкость нефти, сПз
    """
    mu_dead_cp = mu_dead_oil_beggs_robinson(api, t_f)

    if p_psi <= pb_psi:
        return mu_live_oil_beggs_robinson(mu_dead_cp, rs_scf_stb)

    mu_ob_cp = mu_live_oil_beggs_robinson(mu_dead_cp, rsb_scf_stb)
    return mu_oil_above_pb_vasquez_beggs(mu_ob_cp, p_psi, pb_psi)


# ---------------------------------------------------------------------------
# 5. Сжимаемость нефти Co выше Pb — корреляция Vasquez-Beggs
# ---------------------------------------------------------------------------
def co_vasquez_beggs(p_psi: float, rsb_scf_stb: float, gamma_g: float,
                      api: float, t_f: float) -> float:
    """
    Изотермическая сжимаемость нефти Co выше давления насыщения —
    корреляция Vasquez-Beggs (1980).

    Диапазон применимости (field units):
        P: 141 - 9151 psi (выше Pb)
        API: 15.3 - 59.5
        Rsb: 9.3 - 2199 scf/stb
        T: 75 - 320 F
    Диапазон в метрике: P ~10-631 бар, плотность ~745-965 кг/м3,
        Rsb ~1.7-391 м3/м3, T ~24-160 °C

    Параметры
    ---------
    p_psi       : давление, psi (> Pb)
    rsb_scf_stb : газосодержание при давлении насыщения, scf/stb
    gamma_g     : относительная плотность газа
    api         : плотность нефти, °API
    t_f         : температура, °F

    Возвращает
    ----------
    co_per_psi : сжимаемость нефти, 1/psi
    """
    co_per_psi = (
        (-1433.0 + 5.0 * rsb_scf_stb + 17.2 * t_f - 1180.0 * gamma_g + 12.61 * api)
        / (1e5 * p_psi)
    )
    return co_per_psi


