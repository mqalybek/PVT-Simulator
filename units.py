"""
units.py — конвертация единиц измерения между метрической системой (Казахстан)
и field units (США), в которых "исторически зашиты" корреляции Standing,
Vasquez-Beggs, Dranchuk-Abou-Kassem и др.

Все функции в pvt_correlations.py работают ТОЛЬКО в field units:
    - давление: psi
    - температура: °F
    - газосодержание Rs: scf/stb
    - объёмный коэффициент нефти Bo: bbl/stb (rb/stb)
    - объёмный коэффициент газа Bg: rcf/scf (res ft3 / scf)
    - плотность нефти: °API
    - вязкость: сПз (cP) — совпадает в обеих системах, конвертация не нужна
    - сжимаемость: 1/psi

Этот модуль отвечает за пересчёт входа/выхода в метрическую систему для UI.
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# Давление
# ---------------------------------------------------------------------------
# 1 бар = 14.5038 psi (точное определение: 1 bar = 100000 Pa, 1 psi = 6894.757 Pa)
BAR_TO_PSI = 14.5037738

def bar_to_psi(p_bar: float) -> float:
    """Давление: бар -> psi."""
    return p_bar * BAR_TO_PSI


def psi_to_bar(p_psi: float) -> float:
    """Давление: psi -> бар."""
    return p_psi / BAR_TO_PSI


# ---------------------------------------------------------------------------
# Температура
# ---------------------------------------------------------------------------
def c_to_f(t_c: float) -> float:
    """Температура: °C -> °F.  °F = °C * 9/5 + 32"""
    return t_c * 9.0 / 5.0 + 32.0


def f_to_c(t_f: float) -> float:
    """Температура: °F -> °C.  °C = (°F - 32) * 5/9"""
    return (t_f - 32.0) * 5.0 / 9.0


# ---------------------------------------------------------------------------
# Газосодержание Rs (растворённый газ в нефти)
# ---------------------------------------------------------------------------
# 1 м3/м3 (нм3 газа / м3 нефти) = 5.614583 scf/stb
# Вывод: 1 stb = 5.614583 барреля; 1 барр = 0.158987 м3, значит
# 1 stb нефти = 0.158987 м3 нефти, а 1 scf = 0.0283168 м3 газа.
# scf/stb -> м3/м3: (scf * 0.0283168) / (stb * 0.158987) = scf/stb * 0.178108
# Обратный коэффициент: 1 / 0.178108 = 5.614583
RS_M3M3_TO_SCFSTB = 5.614583

def rs_m3m3_to_scf_stb(rs_m3m3: float) -> float:
    """Газосодержание Rs: м3/м3 -> scf/stb."""
    return rs_m3m3 * RS_M3M3_TO_SCFSTB


def rs_scf_stb_to_m3m3(rs_scf_stb: float) -> float:
    """Газосодержание Rs: scf/stb -> м3/м3."""
    return rs_scf_stb / RS_M3M3_TO_SCFSTB


# ---------------------------------------------------------------------------
# Объёмный коэффициент нефти Bo и воды Bw
# ---------------------------------------------------------------------------
# Bo и Bw безразмерны как "объём в пласт. условиях / объём на поверхности".
# 1 м3/м3 = 1 bbl/stb — коэффициент 1:1, т.к. это отношение ОБЪЁМОВ,
# а не абсолютная величина: и числитель, и знаменатель выражены в баррелях
# либо в кубометрах, единицы взаимно сокращаются. Явно оставляем функции,
# чтобы код был единообразным и понятным (а также на случай, если в будущем
# кто-то перепутает м3/баррель на входе).
def bo_m3m3_to_bbl_stb(bo_m3m3: float) -> float:
    """Объёмный коэффициент нефти Bo: м3/м3 -> bbl/stb (коэффициент 1:1)."""
    return bo_m3m3 * 1.0


def bo_bbl_stb_to_m3m3(bo_bbl_stb: float) -> float:
    """Объёмный коэффициент нефти Bo: bbl/stb -> м3/м3 (коэффициент 1:1)."""
    return bo_bbl_stb * 1.0


# Bw ведёт себя аналогично Bo — тоже безразмерное отношение объёмов
bw_m3m3_to_bbl_stb = bo_m3m3_to_bbl_stb
bw_bbl_stb_to_m3m3 = bo_bbl_stb_to_m3m3


# ---------------------------------------------------------------------------
# Объёмный коэффициент газа Bg
# ---------------------------------------------------------------------------
# В field units Bg обычно выражают в rcf/scf (res ft3 газа / scf на поверхности).
# В метрике — м3/м3 (м3 газа в пласте / м3 газа на поверхности при с.у.).
# Так как это тоже отношение объёмов газа в одинаковых физ. условиях числителя
# и знаменателя (пласт/поверхность), коэффициент между rcf/scf и м3/м3 — тоже 1:1
# (кубический фут сокращается с кубическим футом, м3 с м3).
def bg_m3m3_to_rcf_scf(bg_m3m3: float) -> float:
    """Объёмный коэффициент газа Bg: м3/м3 -> rcf/scf (коэффициент 1:1)."""
    return bg_m3m3 * 1.0


def bg_rcf_scf_to_m3m3(bg_rcf_scf: float) -> float:
    """Объёмный коэффициент газа Bg: rcf/scf -> м3/м3 (коэффициент 1:1)."""
    return bg_rcf_scf * 1.0


# Часто Bg также приводят к bbl/Mscf для удобства (1 rcf/scf = 5.614583 bbl/Mscf,
# т.к. 1 Mscf = 1000 scf, а 1 bbl = 5.614583 ft3):
def bg_rcf_scf_to_bbl_mscf(bg_rcf_scf: float) -> float:
    """Объёмный коэффициент газа Bg: rcf/scf -> bbl/Mscf."""
    return bg_rcf_scf * 1000.0 / 5.614583


# ---------------------------------------------------------------------------
# Плотность нефти: кг/м3 <-> °API (через относительную плотность SG)
# ---------------------------------------------------------------------------
def rho_kgm3_to_sg(rho_kgm3: float) -> float:
    """Плотность нефти кг/м3 -> относительная плотность SG (по воде, 1000 кг/м3)."""
    return rho_kgm3 / 1000.0


def sg_to_rho_kgm3(sg: float) -> float:
    """Относительная плотность SG -> плотность нефти, кг/м3."""
    return sg * 1000.0


def sg_to_api(sg: float) -> float:
    """SG -> °API.  API = 141.5/SG - 131.5 (стандартная формула API Gravity)."""
    return 141.5 / sg - 131.5


def api_to_sg(api: float) -> float:
    """°API -> SG.  SG = 141.5 / (API + 131.5)"""
    return 141.5 / (api + 131.5)


def rho_kgm3_to_api(rho_kgm3: float) -> float:
    """Плотность нефти, кг/м3 -> °API (напрямую, через SG)."""
    return sg_to_api(rho_kgm3_to_sg(rho_kgm3))


def api_to_rho_kgm3(api: float) -> float:
    """°API -> плотность нефти, кг/м3 (напрямую, через SG)."""
    return sg_to_rho_kgm3(api_to_sg(api))


# ---------------------------------------------------------------------------
# Сжимаемость
# ---------------------------------------------------------------------------
# Co, Cw измеряются в 1/[единица давления]. Так как давление конвертируется
# через BAR_TO_PSI, сжимаемость конвертируется обратным коэффициентом:
# co [1/psi] = co [1/bar] / BAR_TO_PSI  =>  co [1/bar] = co [1/psi] * BAR_TO_PSI
def compressibility_per_psi_to_per_bar(c_per_psi: float) -> float:
    """Сжимаемость: 1/psi -> 1/бар."""
    return c_per_psi * BAR_TO_PSI


def compressibility_per_bar_to_per_psi(c_per_bar: float) -> float:
    """Сжимаемость: 1/бар -> 1/psi."""
    return c_per_bar / BAR_TO_PSI


# ---------------------------------------------------------------------------
# Солёность пластовой воды: г/л (NaCl-экв) <-> ppm (мг/кг, для пресной воды ~ мг/л)
# ---------------------------------------------------------------------------
def salinity_gpl_to_ppm(salinity_gpl: float) -> float:
    """Солёность: г/л NaCl-экв -> ppm (мг/л ~ мг/кг при плотности воды ~1000 кг/м3)."""
    return salinity_gpl * 1000.0


def salinity_ppm_to_gpl(salinity_ppm: float) -> float:
    """Солёность: ppm -> г/л NaCl-экв."""
    return salinity_ppm / 1000.0


def salinity_ppm_to_wt_pct(salinity_ppm: float) -> float:
    """Солёность: ppm -> % по массе (используется в корреляциях McCain для Bw, Cw)."""
    return salinity_ppm / 10000.0


# ---------------------------------------------------------------------------
# Простые самопроверочные тесты (запускать: python units.py)
# ---------------------------------------------------------------------------
def _run_self_tests() -> None:
    assert abs(bar_to_psi(1) - 14.5038) < 1e-3, "bar_to_psi(1) должен быть ~14.5038"
    assert abs(psi_to_bar(14.5038) - 1) < 1e-3, "psi_to_bar(14.5038) должен быть ~1"

    assert abs(c_to_f(0) - 32) < 1e-9, "0 C = 32 F"
    assert abs(c_to_f(100) - 212) < 1e-9, "100 C = 212 F"
    assert abs(f_to_c(32) - 0) < 1e-9, "32 F = 0 C"
    assert abs(f_to_c(212) - 100) < 1e-9, "212 F = 100 C"

    assert abs(rs_m3m3_to_scf_stb(1) - 5.614583) < 1e-3
    assert abs(rs_scf_stb_to_m3m3(5.614583) - 1) < 1e-3

    assert bo_m3m3_to_bbl_stb(1.25) == 1.25, "Bo конвертируется 1:1"
    assert bo_bbl_stb_to_m3m3(1.25) == 1.25

    assert bg_m3m3_to_rcf_scf(0.005) == 0.005
    assert abs(bg_rcf_scf_to_bbl_mscf(1) - 178.108) < 0.5

    # SG нефти 850 кг/м3 -> SG=0.85 -> API = 141.5/0.85 - 131.5 = 34.94
    api_850 = rho_kgm3_to_api(850)
    assert abs(api_850 - 34.94) < 0.1, f"API для 850 кг/м3 должен быть ~34.94, получили {api_850}"
    # обратное преобразование
    rho_back = api_to_rho_kgm3(api_850)
    assert abs(rho_back - 850) < 0.5

    assert abs(compressibility_per_psi_to_per_bar(1) - 14.5038) < 1e-3
    assert abs(compressibility_per_bar_to_per_psi(14.5038) - 1) < 1e-3

    assert abs(salinity_gpl_to_ppm(30) - 30000) < 1e-9
    assert abs(salinity_ppm_to_gpl(30000) - 30) < 1e-9

    print("units.py: все self-тесты пройдены успешно ✔")


if __name__ == "__main__":
    _run_self_tests()
